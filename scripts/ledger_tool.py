def main(argv=None):
    parser = build_parser()
    args = parser.parse_args(argv)
    args.func(args)
    if getattr(args, "ledger", None) and args.command not in {"context", "serve", "history"}:
        from ledger_core.services.history import flush_auto_sync
        result = flush_auto_sync(args.ledger)
        if result:
            print("Git sync: " + result.get("state", "pending"), file=sys.stderr)

if __name__ == "__main__":
    main()
